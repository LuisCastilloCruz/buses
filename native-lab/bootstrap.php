<?php

// Boot the REAL MultiFactura application, routes, authentication and view composers.
$root = dirname(__DIR__);
$runtime = $root . '/.native-runtime';
require $root . '/vendor/autoload.php';
foreach (['CONFIG', 'SERVICES', 'PACKAGES', 'ROUTES'] as $cache) {
    $_ENV['APP_' . $cache . '_CACHE'] = $runtime . '/cache/' . strtolower($cache) . '.php';
}
$app = (require $root . '/bootstrap/app.php');
$app->useEnvironmentPath($runtime);
$app->loadEnvironmentFrom('.no-original-env');
$app->useStoragePath($runtime . '/storage');
$app->afterBootstrapping(Illuminate\Foundation\Bootstrap\LoadConfiguration::class, function ($app) use($root, $runtime) {
    $s = json_decode(file_get_contents($runtime . '/settings.json'), true);
    if (($s['purpose'] ?? '') !== 'multifactura-native-v6' || $s['root'] !== str_replace('\\', '/', realpath($root))) {
        throw new RuntimeException('Invalid native lab settings');
    }
    $db = ['driver' => 'mysql', 'host' => '127.0.0.1', 'port' => 13321, 'database' => 'mf_v6_system', 'username' => $s['user'], 'password' => $s['password'], 'charset' => 'utf8mb4', 'collation' => 'utf8mb4_unicode_ci', 'prefix' => '', 'strict' => false, 'engine' => 'InnoDB'];
    $probe = new PDO('mysql:host=127.0.0.1;port=13321;dbname=mf_v6_system', $s['user'], $s['password'], [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
    $m = $probe->query('SELECT @@port port,@@datadir datadir')->fetch(PDO::FETCH_ASSOC);
    if ((int) $m['port'] !== 13321 || strtolower(str_replace('\\', '/', $m['datadir'])) !== strtolower($s['root'] . '/.native-runtime/mysql-data/')) {
        throw new RuntimeException('Unsafe server');
    }
    $app->detectEnvironment(function () {
        return 'local';
    });
    $app['config']->set('database.connections', ['system' => $db]);
    $app['config']->set('database.default', 'system');
    foreach (['app.env' => 'local', 'app.debug' => true, 'debugbar.enabled' => false, 'app.key' => $s['key'], 'app.url' => 'http://localhost:8878', 'app.timezone' => 'America/Lima', 'tenant.prefix_database' => 'mf_v6', 'tenant.app_url_base' => 'localhost', 'tenant.force_https' => false, 'cache.default' => 'array', 'session.driver' => 'file', 'session.files' => $runtime . '/storage/framework/sessions', 'session.domain' => null, 'session.cookie' => 'mf_v6_session', 'mail.driver' => 'log', 'queue.failed.database'=>'system', 'queue.failed.table'=>'aireception_failed_jobs', 'queue.default' => 'database', 'broadcasting.default' => 'log', 'aireception.meta_sandbox_enabled'=>true, 'aireception.reminders_simulation_enabled'=>true, 'aireception.native_enabled' => true, 'aireception.enabled' => false, 'aireception.external_connections_enabled' => false, 'tattooinbox.ai.enabled' => false, 'tattooinbox.meta.require_signature'=>true, 'tattooinbox.meta.verify_token'=>null, 'tattooinbox.meta.page_access_token'=>null, 'tattooinbox.meta.app_secret' => null, 'tattooinbox.meta.whatsapp_access_token' => null, 'odontologia.clinical_records_enabled' => true, 'native_lab.enabled' => true, 'tenancy.hostname.cache' => false, 'tenancy.website.cache' => false] as $k => $v) {
        $app['config']->set($k, $v);
    }
});
// An authorization file is never shipped or generated by tests. CLI workers only.
$app->afterBootstrapping(Illuminate\Foundation\Bootstrap\LoadConfiguration::class, function($app)use($runtime){
 $file=$runtime.'/sandbox-authorization.json';if(PHP_SAPI!=='cli'||!is_file($file))return;
 $a=json_decode(file_get_contents($file),true);
 if(!is_array($a)||($a['purpose']??'')!=='multifactura-v6-authorized-sandbox'||($a['authorized']??false)!==true||!is_int($a['expires_at']??null)||$a['expires_at']<=time()||$a['expires_at']>time()+604800)throw new RuntimeException('Invalid sandbox authorization.');
 foreach(['gateway','gateway_channels','channel_actors','audio','reminder_templates'] as $key)$app['config']->set('aireception.'.$key,$a[$key]??[]);
 $app['config']->set('aireception.gateway_authorized',true);$app['config']->set('aireception.external_connections_enabled',true);$app['config']->set('aireception.channel_processing_enabled',true);$app['config']->set('aireception.v5_transport_mode','sandbox');
});
$app->afterBootstrapping(Illuminate\Foundation\Bootstrap\RegisterProviders::class, function ($app) {
    require_once __DIR__.'/ReservedDatabase.php';
    $app->bind(Hyn\Tenancy\Contracts\Database\PasswordGenerator::class, NativeReservedPassword::class);
    $app->make('tenancy.db.drivers')->put('mysql', NativeReservedDatabase::class);
});
return $app;
